"""Generate the serial motor register-name type from rustypot's servo definitions.

Run with:

    uv run --no-project --with "rustypot>=1.13.1,<2.0.0" python scripts/generate_motor_registers.py

Use ``--check`` to fail when the checked-in generated module is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import rustypot


# One model per distinct rustypot definition. Add a probe when rustypot adds a definition.
SERVO_PROBES = (
    "ax-12w",
    "mx-28",
    "xl-320",
    "xl330-m077",
    "xl430-w250",
    "scs0009",
    "scs0043",
    "sts3215",
    "orbita2d-foc",
    "orbita2d-poulpe",
    "orbita3d-foc",
    "orbita3d-poulpe",
)
REGISTER_MODULE = Path(__file__).resolve().parents[1] / "src" / "lerobot" / "motors" / "registers.py"


def find_servo(name: str) -> rustypot.ServoDefinition:
    """Find the rustypot definition for a probe model."""
    import rustypot

    if (found := rustypot.find_model(name)) is None:
        raise RuntimeError(f"rustypot has no servo model '{name}'; update SERVO_PROBES")
    return found[1]


def collect_register_names() -> list[str]:
    """Return every register name in lowercase, sorted and deduplicated."""
    names = {register.name.lower() for probe in SERVO_PROBES for register in find_servo(probe).registers()}
    return sorted(names)


def spellings(name: str) -> tuple[str, str, str]:
    """Return the standard lowercase, title-case and uppercase spellings."""
    title_case = "_".join(part.capitalize() for part in name.split("_"))
    return name, title_case, name.upper()


def render_module(names: list[str]) -> str:
    """Render the generated Literal module."""
    lines = [
        "#!/usr/bin/env python",
        "",
        "# Copyright 2026 The HuggingFace Inc. team. All rights reserved.",
        "#",
        '# Licensed under the Apache License, Version 2.0 (the "License");',
        "# you may not use this file except in compliance with the License.",
        "# You may obtain a copy of the License at",
        "#",
        "#     http://www.apache.org/licenses/LICENSE-2.0",
        "#",
        "# Unless required by applicable law or agreed to in writing, software",
        '# distributed under the License is distributed on an "AS IS" BASIS,',
        "# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        "# See the License for the specific language governing permissions and",
        "# limitations under the License.",
        "",
        "# Generated by scripts/generate_motor_registers.py. Do not edit by hand.",
        "from typing import Literal",
        "",
        "RegisterName = Literal[",
    ]
    for name in names:
        lines.extend(f'    "{spelling}",' for spelling in spellings(name))
    lines.extend(["]", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check whether the generated module is current")
    args = parser.parse_args()

    source = render_module(collect_register_names())
    if args.check:
        if REGISTER_MODULE.exists() and REGISTER_MODULE.read_text() == source:
            print(f"{REGISTER_MODULE} is up to date.")
            return 0
        print(f"{REGISTER_MODULE} is stale; regenerate it.", file=sys.stderr)
        return 1

    REGISTER_MODULE.write_text(source)
    print(f"Wrote {REGISTER_MODULE}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
